import { supabase } from './supabase'

/* ---- storageKeys.js ---- */
export function readAndMigrateStorageItem(key, legacyKey) {
  const currentValue = localStorage.getItem(key)
  if (currentValue !== null) return currentValue

  const legacyValue = localStorage.getItem(legacyKey)
  if (legacyValue !== null) {
    localStorage.setItem(key, legacyValue)
    localStorage.removeItem(legacyKey)
  }
  return legacyValue
}

/* ---- circleHash.js ---- */

const ADJECTIVES = ['Brave', 'Calm', 'Kind', 'Bright', 'Steady', 'Quiet', 'Clear', 'Bold']
const ANIMALS = ['Otter', 'Falcon', 'Lion', 'Dolphin', 'Eagle', 'Panda', 'Fox', 'Wolf']

// Server-issued anonymous identity. The hash is generated by the
// ensure_circle_identity() RPC and is immutable once set.
export async function ensureCircleHash() {
  const { data, error } = await supabase.rpc('ensure_circle_identity')
  if (error) {
    console.error('Failed to ensure circle identity:', error)
    throw error
  }
  return data
}
